import assert from "node:assert/strict";
import { compactContextMetadata } from "../dist/context-capsule.js";
const capsule = {globalMemory:[],globalState:[],projectMemory:[],reusableSkills:[],projectArchitecture:[]};
const tags=["artifact:l3","project:memhub","confidence:0.9","evidence:l2:old:r1","provenance:account:private"];
capsule.projectMemory.push({id:"truth",evidenceRef:"l3:truth:r2",content:"Current rule 当前规则",authority:"remembered",scope:"project",source:"memory",provenance:{tags,originalTagCount:100,hydration:{evidence_ref:"l3:truth:r2"},memoryLayer:"L3"}});
capsule.projectMemory.push({id:"unversioned",content:"keep legacy provenance",provenance:{tags}});
capsule.projectArchitecture.push({id:"map",source:"project-architecture-cognitive-map",content:"map",authority:"derived",provenance:{fingerprint:"exact-map",source_evidence_refs:Array.from({length:20},(_,i)=>"code:"+i)}});
const before=structuredClone(capsule);
compactContextMetadata(capsule);
assert.equal(capsule.projectMemory[0].content,before.projectMemory[0].content);
assert.equal(capsule.projectMemory[0].evidenceRef,before.projectMemory[0].evidenceRef);
assert.deepEqual(capsule.projectMemory[0].provenance.hydration,before.projectMemory[0].provenance.hydration);
assert.deepEqual(capsule.projectMemory[0].provenance.tags,tags.slice(0,3));
assert.equal(capsule.projectMemory[0].provenance.originalTagCount,100);
assert.deepEqual(capsule.projectMemory[1],before.projectMemory[1]);
assert.equal(capsule.projectArchitecture[0].provenance.source_evidence_refs.length,4);
assert.equal(capsule.projectArchitecture[0].provenance.source_evidence_refs_count,20);
assert.equal(capsule.projectArchitecture[0].provenance.fingerprint,"exact-map");
const once=structuredClone(capsule); compactContextMetadata(capsule);
assert.deepEqual(capsule,once);
assert.deepEqual(tags,before.projectMemory[1].provenance.tags);
console.log("context-metadata: exact identity, contents, authority, legacy fallback, counts and idempotence passed");
